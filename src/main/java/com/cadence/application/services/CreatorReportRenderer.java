package com.cadence.application.services;

import com.cadence.application.results.CreatorReportSnapshot;
import com.cadence.domain.CreatorReport;
import java.nio.charset.StandardCharsets;
import java.util.UUID;
import org.springframework.stereotype.Component;

/** Fixed static markup: all variable values are text, never URLs, scripts or trusted HTML. */
@Component
public class CreatorReportRenderer {
  public byte[] render(UUID id, CreatorReportSnapshot s) {
    var h =
        new StringBuilder(
            "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><title>Cadence performance report</title></head><body><main><h1>Cadence performance report</h1>");
    text(h, "Report", id);
    text(h, "Captured at", s.capturedAt());
    source(h, s.strategy());
    text(
        h,
        "Window",
        s.request().fromDate()
            + " to "
            + s.request().untilDate()
            + " (exclusive); "
            + s.request().timezone()
            + "; "
            + s.request().platform()
            + "; "
            + s.request().bucket());
    text(h, "Formula", s.formulaVersion());
    text(h, "Timezone rules", s.rulesVersion());
    text(
        h,
        "Coverage",
        "candidate="
            + s.candidateRows()
            + ", selected="
            + s.selectedRows()
            + ", incompatible windows="
            + s.incompatibleWindows()
            + ", duplicate snapshots="
            + s.duplicateSnapshots()
            + ", skipped local days="
            + s.skippedLocalDays());
    text(h, "Disclosure", s.caveats());
    h.append("<h2>Performance at capture</h2>");
    for (var g : s.groups()) {
      h.append("<section><h3>")
          .append(escape(g.pillarName() == null ? "Unknown pillar" : g.pillarName()))
          .append("</h3>");
      text(
          h,
          "Exact UTC window",
          g.windowFrom() + " / " + g.windowUntil() + "; " + g.windowSeconds() + " seconds");
      text(h, "Posts / stale rows", g.posts() + " / " + g.staleRows());
      for (var r : g.rates()) {
        h.append("<h4>").append(escape(r.formula())).append("</h4>");
        text(h, "Percent", r.percent() == null ? "Missing / undefined" : r.percent() + "%");
        text(h, "Numerator total", known(r.numeratorTotal()));
        text(h, "Denominator total", known(r.denominatorTotal()));
        text(
            h,
            "Coverage",
            r.knownPairs()
                + " known pairs; "
                + r.usablePosts()
                + " usable Posts; "
                + r.missingPairs()
                + " missing; "
                + r.zeroDenominatorPairs()
                + " zero denominator; "
                + r.inconsistentPairs()
                + " inconsistent; "
                + r.stalePairs()
                + " stale");
        text(h, "Comparison eligible", r.comparisonEligible());
        text(h, "Issues", r.issues());
        text(
            h,
            "Minimum sample",
            r.minimumPosts() + " Posts; denominator " + r.minimumDenominator());
      }
      observations(h, g.sources());
      h.append("</section>");
    }
    h.append("<h2>Historical recommendations</h2>");
    if (s.recommendations().isEmpty())
      text(h, "Recommendations", "None selected. No advice generated by this report.");
    for (var a : s.recommendations()) {
      h.append("<section><h3>Hypothesis</h3>");
      text(h, "Recommendation", a.id());
      text(h, "Captured at", a.capturedAt());
      text(h, "Original snapshot checksum", a.snapshotChecksum());
      source(h, a.strategy());
      text(h, "Origin", a.attribution().origin());
      text(h, "Rule", a.attribution().ruleVersion());
      text(h, "Provider", a.attribution().provider());
      text(h, "Model", known(a.attribution().modelVersion()));
      text(h, "Prompt version", known(a.attribution().promptVersion()));
      text(h, "Confidence", a.confidence());
      text(h, "Claim type", a.claimType());
      text(h, "Explanation", a.explanation());
      text(h, "Uncertainty", a.uncertainty());
      text(h, "Relation to report metrics", a.relationToCapturedMetrics());
      observations(h, a.supportingObservations());
      h.append("</section>");
    }
    h.append("</main></body></html>");
    var bytes = h.toString().getBytes(StandardCharsets.UTF_8);
    if (bytes.length > CreatorReport.MAX_BYTES)
      throw new com.cadence.domain.CreatorReportOutputException();
    return bytes;
  }

  private void observations(
      StringBuilder h, java.util.List<CreatorReportSnapshot.Observation> rows) {
    h.append("<h4>Supporting observations</h4><ul>");
    for (var row : rows) {
      h.append("<li><details><summary>Post ").append(escape(row.postId())).append("</summary>");
      text(h, "Observation", row.id());
      text(h, "Metric revision", row.revision());
      text(h, "Value checksum", row.checksum());
      text(h, "Source time", row.observedAt());
      text(h, "Ingestion time", row.ingestedAt());
      text(h, "Origin", row.origin());
      text(
          h,
          "Attribution ID / version",
          known(row.attributionId()) + " / " + known(row.attributionVersion()));
      text(
          h,
          "Post revision ID / version",
          known(row.postRevisionId()) + " / " + known(row.postRevisionVersion()));
      text(h, "Content checksum", known(row.contentChecksum()));
      text(h, "Pillar", known(row.pillarId()));
      text(h, "Format", known(row.postFormat()));
      text(h, "Reach", known(row.reach()));
      text(h, "Engagement", known(row.engagement()));
      text(h, "Saves", known(row.saves()));
      text(h, "Signups", known(row.signups()));
      text(h, "Profile to site clicks", known(row.profileToSiteClicks()));
      h.append("</details></li>");
    }
    h.append("</ul>");
  }

  private String known(Object value) {
    return value == null ? "Missing / unknown" : String.valueOf(value);
  }

  private void source(StringBuilder h, CreatorReportSnapshot.Source s) {
    text(h, "Strategy", s.id());
    text(h, "Strategy revision / version", s.revision() + " / " + s.version());
    text(h, "Strategy checksum", s.checksum());
  }

  private void text(StringBuilder h, String label, Object value) {
    h.append("<p><strong>")
        .append(escape(label))
        .append(": </strong>")
        .append(escape(value))
        .append("</p>");
  }

  static String escape(Object value) {
    return String.valueOf(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\"", "&quot;")
        .replace("'", "&#39;");
  }
}
