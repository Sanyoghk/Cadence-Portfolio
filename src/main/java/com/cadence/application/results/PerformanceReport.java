package com.cadence.application.results;

import com.cadence.domain.*;
import java.time.*;
import java.util.*;

public record PerformanceReport(
    String formulaVersion,
    UUID brandId,
    UUID workspaceId,
    String timezone,
    String rulesVersion,
    LocalDate fromDate,
    LocalDate untilDate,
    Instant generatedAt,
    PerformanceQuery.Dimension dimension,
    PerformanceQuery.Bucket bucket,
    int page,
    int size,
    int totalGroups,
    int candidateRows,
    int selectedRows,
    int duplicateSnapshots,
    int incompatibleWindows,
    int skippedLocalDays,
    long staleAfterSeconds,
    String snapshotChecksum,
    List<String> caveats,
    List<PerformanceGroup> items) {
  public record PerformanceContribution(
      UUID observationId,
      UUID postId,
      int metricRevision,
      String valueChecksum,
      Instant observedAt,
      Instant ingestedAt,
      UUID importId,
      String rawChecksum,
      String origin,
      UUID ingestedBy,
      UUID strategyId,
      int strategyRevision,
      String strategyChecksum,
      UUID sourceApprovedBy,
      Instant sourceApprovedAt,
      UUID attributionId,
      Integer attributionNumber,
      UUID postRevisionId,
      Long postRevisionVersion,
      String contentChecksum,
      PostFormat format,
      String pillarId,
      String pillarOrigin,
      UUID attributedBy,
      Instant attributedAt,
      Long reach,
      Long engagement,
      Long saves,
      Long signups,
      Long profileToSiteClicks) {
    public static PerformanceContribution from(PerformanceSample s) {
      return new PerformanceContribution(
          s.observationId(),
          s.postId(),
          s.revisionNumber(),
          s.valueChecksum(),
          s.observedAt(),
          s.ingestedAt(),
          s.importId(),
          s.rawChecksum(),
          s.origin(),
          s.ingestedBy(),
          s.strategyId(),
          s.strategyRevision(),
          s.strategyChecksum(),
          s.sourceApprovedBy(),
          s.sourceApprovedAt(),
          s.attributionId(),
          s.attributionNumber(),
          s.postRevisionId(),
          s.postRevisionVersion(),
          s.contentChecksum(),
          s.format(),
          s.pillarId(),
          s.pillarOrigin(),
          s.attributedBy(),
          s.attributedAt(),
          s.reach(),
          s.engagement(),
          s.saves(),
          s.signups(),
          s.profileToSiteClicks());
    }
  }

  public record PerformanceGroup(
      LocalDate date,
      Instant windowFrom,
      Instant windowUntil,
      long windowSeconds,
      PlaybookContent.Channel platform,
      UUID pillarStrategyId,
      Integer pillarStrategyRevision,
      String pillarId,
      String pillarName,
      PostFormat format,
      int posts,
      int staleRows,
      String comparisonKey,
      List<PerformanceMetrics.PerformanceRate> rates,
      List<PerformanceContribution> sources) {}
}
